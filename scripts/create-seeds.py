def trap(label, plausible, pivot, when, rule, q, answer, expr, explanation):
    return dict(
        label=label,
        why_plausible=plausible,
        first_wrong_pivot=pivot,
        counterfactual_valid_when=when,
        avoidance_rule=rule,
        recovery_check=dict(
            question=q,
            answer=answer,
            expression=expr,
            target_expression=expr,
            explanation=explanation,
        ),
    )


def item(
    id,
    exam,
    subject,
    topic,
    prompt,
    context,
    expressions,
    latex,
    key,
    solution,
    traps,
    beta=120,
    unit=(0, 0, 0),
    b=0,
):
    options = []
    wrong = iter(traps)
    for k, (e, l) in enumerate(zip(expressions, latex)):
        oid = "ABCD"[k]
        options.append(
            dict(
                id=oid,
                latex=l,
                expression=e,
                derived_expression=e,
                unit=list(unit),
                slope=1.2 if oid == key else [-0.7, 0.35, -0.2, 0.5][k],
                intercept=0.0,
                trap=None if oid == key else next(wrong),
            )
        )
    return dict(
        schema_version="targetjee.item.v2",
        id=id,
        exam=exam,
        subject=subject,
        topic=topic,
        prompt=prompt,
        context=context,
        options=options,
        correct_id=key,
        answer_expression=expressions["ABCD".index(key)],
        solution=solution,
        domain={},
        expected_unit=list(unit),
        diagram_anchors=[],
        beta_seconds=beta,
        alpha=1.0,
        a=1.0,
        b=b,
        c=0.25,
        positive_marks=4,
        negative_marks=1 if exam == "main" else 2,
        parameter_source="illustrative",
    )


